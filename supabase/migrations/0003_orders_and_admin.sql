-- ============================================================================
-- 0003_orders_and_admin.sql
--
-- Authoritative schema for the order backend, the admin allowlist and the
-- notification outbox introduced in Prompt 11.
--
-- Tables:
--   * `orders`               – one row per placed order
--   * `order_items`          – line items that snapshot the product, size,
--                              colour, unit price and line subtotal
--   * `order_status_history` – audit trail of every status transition
--   * `order_notifications`  – durable outbox for the store-owner email
--   * `admin_allowlist`      – explicit list of customer uuids that may
--                              access the `/admin` area
--
-- Design notes:
--   * All money is stored in minor units (paisa for BDT) so totals never
--     suffer from floating-point drift.
--   * `order_number` is generated by a `SECURITY DEFINER` function that
--     reads the next value from a Postgres sequence and formats it as
--     `MF-<n>`. The unique index guarantees the value cannot collide.
--   * `idempotency_key` is scoped per customer so two different customers
--     may reuse the same key, but a single customer retrying the same
--     key never creates a second order.
--   * The customer-facing RLS policies match the access model in the
--     application: customers can only read their own orders. Admin
--     reads/writes go through the service role and never through the
--     authenticated client.
--   * The `is_admin()` function is the single source of truth for
--     authorization. It reads from `admin_allowlist` and is invoked
--     inside RLS policies on the order tables.
--
-- How to apply:
--   1. Open the Supabase dashboard, then `SQL Editor`.
--   2. Paste the contents of this file and run.
--   3. Grant the first administrator by inserting a row into
--      `admin_allowlist(user_id, granted_by)` where `user_id` is the
--      `auth.users.id` of the store owner. This must be done through the
--      service role; the RLS policy refuses inserts from the anon key.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Helper: minimum order totals.
-- ----------------------------------------------------------------------------

create sequence if not exists public.order_number_seq;

-- ----------------------------------------------------------------------------
-- Orders
-- ----------------------------------------------------------------------------

create table if not exists public.orders (
  id                    uuid primary key default gen_random_uuid(),
  order_number          text not null,
  user_id               uuid not null references auth.users(id) on delete restrict,
  customer_name         text not null,
  customer_phone        text not null,
  customer_email        text,

  -- Address snapshot. The address is the one the customer provided at the
  -- time of the order — never their current saved address.
  recipient_name        text not null,
  phone                 text not null,
  district              text not null,
  locality              text,
  address_line          text not null,
  additional_details    text,
  postal_code           text,
  delivery_zone         text not null check (delivery_zone in ('inside_dhaka', 'outside_dhaka')),
  delivery_instructions text,

  -- Money (minor units). The BDT taka figures elsewhere are derived from
  -- these integer values for display.
  subtotal_paisa        bigint not null check (subtotal_paisa >= 0),
  delivery_fee_paisa    bigint not null check (delivery_fee_paisa >= 0),
  total_paisa           bigint not null check (total_paisa >= 0),
  currency              text not null default 'BDT',

  -- Lifecycle.
  payment_method        text not null check (payment_method in ('cod', 'bkash')),
  payment_status        text not null default 'pending'
                          check (payment_status in ('pending', 'awaiting_verification', 'paid', 'failed', 'refunded')),
  order_status          text not null default 'pending_confirmation'
                          check (order_status in (
                            'pending_confirmation',
                            'confirmed',
                            'processing',
                            'shipped',
                            'delivered',
                            'cancelled'
                          )),
  bkash_reference       text,
  cancelled_at          timestamptz,

  -- Idempotency. Scoped per customer (composite uniqueness).
  idempotency_key       text not null,
  idempotency_hash      text not null,

  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create unique index if not exists orders_order_number_idx
  on public.orders (order_number);

create index if not exists orders_user_idx
  on public.orders (user_id, created_at desc);

create unique index if not exists orders_user_idempotency_idx
  on public.orders (user_id, idempotency_key);

create index if not exists orders_status_idx
  on public.orders (order_status, created_at desc);

create index if not exists orders_payment_status_idx
  on public.orders (payment_status, created_at desc);

drop trigger if exists set_orders_updated_at on public.orders;
create trigger set_orders_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- Order items
-- ----------------------------------------------------------------------------

create table if not exists public.order_items (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null references public.orders(id) on delete cascade,
  product_id          text not null,
  product_slug        text,
  product_name        text not null,
  size                text,
  color               text,
  quantity            integer not null check (quantity > 0),
  unit_price_paisa    bigint not null check (unit_price_paisa >= 0),
  line_total_paisa    bigint not null check (line_total_paisa >= 0),
  image_alt           text,
  image_aspect_ratio  numeric,
  created_at          timestamptz not null default now()
);

create index if not exists order_items_order_idx
  on public.order_items (order_id);

-- ----------------------------------------------------------------------------
-- Order status history
-- ----------------------------------------------------------------------------

create table if not exists public.order_status_history (
  id           uuid primary key default gen_random_uuid(),
  order_id     uuid not null references public.orders(id) on delete cascade,
  from_status  text,
  to_status    text not null,
  actor        text not null check (actor in ('customer', 'admin', 'system')),
  actor_id     uuid,
  note         text,
  created_at   timestamptz not null default now()
);

create index if not exists order_status_history_order_idx
  on public.order_status_history (order_id, created_at);

-- ----------------------------------------------------------------------------
-- Notification outbox
-- ----------------------------------------------------------------------------

create table if not exists public.order_notifications (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null references public.orders(id) on delete cascade,
  notification_type   text not null check (notification_type in ('new_order_owner')),
  recipient           text not null,
  status              text not null default 'pending'
                        check (status in ('pending', 'sent', 'failed')),
  attempt_count       integer not null default 0 check (attempt_count >= 0),
  last_attempted_at   timestamptz,
  last_error          text,
  provider_message_id text,
  sent_at             timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists order_notifications_order_idx
  on public.order_notifications (order_id, created_at);

create index if not exists order_notifications_status_idx
  on public.order_notifications (status, created_at);

drop trigger if exists set_order_notifications_updated_at on public.order_notifications;
create trigger set_order_notifications_updated_at
  before update on public.order_notifications
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- Admin allowlist
-- ----------------------------------------------------------------------------

create table if not exists public.admin_allowlist (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  granted_by  uuid references auth.users(id) on delete set null,
  granted_at  timestamptz not null default now(),
  note        text
);

-- ----------------------------------------------------------------------------
-- Helper: is the current authenticated user an administrator?
-- Used by RLS policies below. SECURITY DEFINER so the policy can read
-- the allowlist on behalf of the calling user.
-- ----------------------------------------------------------------------------

create or replace function public.is_admin(uid uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.admin_allowlist where user_id = uid
  );
$$;

grant execute on function public.is_admin(uuid) to authenticated, anon;

-- ----------------------------------------------------------------------------
-- RLS for `orders`
-- ----------------------------------------------------------------------------

alter table public.orders enable row level security;

drop policy if exists "Customers can read their own orders" on public.orders;
create policy "Customers can read their own orders"
  on public.orders
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Admins can read every order" on public.orders;
create policy "Admins can read every order"
  on public.orders
  for select
  to authenticated
  using (public.is_admin(auth.uid()));

-- Inserts, updates and deletes are intentionally only possible through
-- the service role. Customers must use the order-placement server
-- action which validates the request and writes through the service
-- role. The RLS layer refuses any client-side insert/update/delete.

-- ----------------------------------------------------------------------------
-- RLS for `order_items`
-- ----------------------------------------------------------------------------

alter table public.order_items enable row level security;

drop policy if exists "Customers can read their own order items" on public.order_items;
create policy "Customers can read their own order items"
  on public.order_items
  for select
  to authenticated
  using (
    exists (
      select 1 from public.orders o
      where o.id = order_items.order_id and o.user_id = auth.uid()
    )
  );

drop policy if exists "Admins can read every order item" on public.order_items;
create policy "Admins can read every order item"
  on public.order_items
  for select
  to authenticated
  using (public.is_admin(auth.uid()));

-- ----------------------------------------------------------------------------
-- RLS for `order_status_history`
