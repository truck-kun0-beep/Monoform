-- ----------------------------------------------------------------------------
-- RLS for `admin_allowlist`
-- ----------------------------------------------------------------------------

alter table public.admin_allowlist enable row level security;

-- A user may read their own row so the client can render a friendly
-- "you are an administrator" badge without exposing the rest of the
-- allowlist.
drop policy if exists "Users can read their own admin row" on public.admin_allowlist;
create policy "Users can read their own admin row"
  on public.admin_allowlist
  for select
  to authenticated
  using (auth.uid() = user_id);

-- Only the service role can write to the allowlist. This stops a
-- regular customer from inserting themselves as an administrator.

-- ----------------------------------------------------------------------------
-- Order-number generator. Pulls the next value from the sequence and
-- formats it as `MF-<n>`. SECURITY DEFINER so the same function can be
-- used by both the order-placement path and the admin tools.
-- ----------------------------------------------------------------------------

create or replace function public.next_order_number()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  next_value bigint;
  formatted  text;
begin
  next_value := nextval('public.order_number_seq');
  formatted := 'MF-' || lpad(next_value::text, 6, '0');
  return formatted;
end;
$$;

grant execute on function public.next_order_number() to authenticated, service_role;
